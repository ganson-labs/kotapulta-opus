// Уровни. Координаты в метрах; земля — y = 0. Для прямоугольников задаём низ (b),
// центр по y вычисляется. Всё стоит ровно, без наложений: башни спокойно спят,
// пока в них не прилетит кот.

const R = (t, x, b, w, h, extra) => ({ t, x, y: b + h / 2, w, h, ...extra });
const box = (x, b, w = 1.6, h = 1.3, extra) => R('box', x, b, w, h, extra);
const crate = (x, b, s = 1.2, extra) => R('crate', x, b, s, s, extra);
const plank = (x, b, w = 3.6, h = 0.3) => R('plank', x, b, w, h);
const post = (x, b, h = 2, w = 0.35) => R('plank', x, b, w, h);
const brick = (x, b, w = 1.2, h = 0.6) => R('brick', x, b, w, h);
const pot = (x, b, v = 0) => R('pot', x, b, 0.8, 0.9, { v });
const pillow = (x, b, w = 1.9, h = 0.5, v = 0) => R('pillow', x, b, w, h, { v });
const yarn = (x, b, r = 0.45, v = 0) => ({ t: 'yarn', x, y: b + r, r, v });
const fish = (x, b) => ({ t: 'fish', x, y: b + 0.15 });
const sleeper = (x, b, s = 1, extra) => ({ t: 'sleeper', x, y: b + 0.44 * s, s, ...extra });

